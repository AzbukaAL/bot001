"""Расчёты электрики — кодом, не моделью (09.10.2026). cos φ = 1 (так считал инженер в P8–P10; при cos φ 0,95 ток выше ~5 %).
- ток по мощности: 1 фаза I = P / U (U = 220 В); 3 фазы I = P / (√3 · U) (U = 380 В);
- ближайший стандартный номинал автомата (ряд по ГОСТ IEC 60898-1: 6…125 А) — не меньше расчётного тока;
- обратный расчёт: какую мощность допускает номинал.
Числа округляются как в ответах инженера: ток — до 0,1 А, мощность — до 0,1 кВт.
"""
import math, re

U1, U3 = 220, 380
# 15.10: опросный лист не заполнен — ток котла посчитать можно, а вывод о подключении делать нельзя (нет лимита на фазу).
# Эта строка — и факт для ответа, и признак для answer.py: пункт уходит инженеру с перечнем нужных данных.
NO_ALLOC = ("Выделенная мощность и фазность в опросном листе не заполнены — какое подключение подходит "
            "для этого объекта, по ним не проверено.")
RATINGS = [6, 10, 13, 16, 20, 25, 32, 40, 50, 63, 80, 100, 125]

def current(p_kw, phases):
    return p_kw * 1000 / (U1 if phases == 1 else math.sqrt(3) * U3)

def rating(i):
    return next((r for r in RATINGS if r >= i - 1e-9), None)

def power(i, phases):
    return i * (U1 if phases == 1 else math.sqrt(3) * U3) / 1000

def fmt(x, nd=1):
    return f"{x:.{nd}f}".replace(".", ",")

def lines_for(p_kw, phases, ratings_mentioned=()):
    """Строки расчёта для ответа (каждая — факт из кода) и сами числа."""
    i = current(p_kw, phases); r = rating(i)
    f = "I = P / U" if phases == 1 else "I = P / (√3 · U)"
    u = U1 if phases == 1 else U3
    L = [f"{fmt(p_kw, 0)} кВт, {'одна фаза' if phases == 1 else 'три фазы'} ({u} В), cos φ = 1: {f} = {int(p_kw * 1000)} / "
         f"{'' if phases == 1 else '(1,732 · '}{u}{'' if phases == 1 else ')'} ≈ {fmt(i)} А → ближайший стандартный номинал автомата {r} А."]
    rel = sorted(set(ratings_mentioned))
    rel = [m for m in rel if m != r and (r / 2 <= m <= r * 2 or m == min(rel))]   # уместные: соседние с расчётным и самый малый (стоящий)
    for m in rel:
        L.append(f"Автомат {m} А при {'одной фазе' if phases == 1 else 'трёх фазах'} допускает мощность до ≈ {fmt(power(m, phases))} кВт.")
    return L

def from_claim(claim):
    """Расчёт по претензии: мощность (кВт), фазность и упомянутые номиналы (А). Пусто — если расчёт неуместен."""
    t = claim.replace(",", ".")
    kw = [float(x) for x in re.findall(r"(\d+(?:\.\d+)?)\s*кВт", t)]
    amps = [int(x) for x in re.findall(r"(\d{2,3})\s*А\b", t) if int(x) in RATINGS]
    if not kw: return []
    out = []
    three = re.search(r"тр[её]х\s*фаз|3\s*фаз|380", t, re.I); one = re.search(r"одн[аоуй]\w*\s*фаз|1\s*фаз|220", t, re.I)
    for p in kw[:1]:
        if three or not one: out += lines_for(p, 3, amps)
        if one: out += lines_for(p, 1, amps)
    return out

def from_project(obj, claim):
    """Расчёт по ДАННЫМ ПРОЕКТА (15.10.2026): мощность котла — из теплотехнического расчёта, выделенная мощность
    и фазность — из опросного листа. Нужна электрическая/отопительная тема и мощность котла; иначе [].
    Лимит на одну фазу = выделенная мощность / число фаз — так считал инженер (15 кВт на 3 фазы → 5 кВт на фазу)."""
    if not obj or not re.search(r"кот[ёел]л|кВт|фаз|220|380|мощност|вольт", claim, re.I): return []
    items = obj.get("items") or []
    def val(rx):
        return next((str(i.get("описание") or "") for i in items if re.search(rx, str(i.get("позиция") or ""), re.I)), "")
    def num(t):
        m = re.search(r"(\d+(?:[.,]\d+)?)", t or ""); return float(m.group(1).replace(",", ".")) if m else None
    mk = val(r"^Мощность котла")   # ^ — иначе совпадает и «Требуемая мощность котла»; одна позиция «требуемая …, фактическая устанавливаемая …» (project_docs.teplo)
    def after(word, t):
        m = re.search(word + r"[^\d]{0,40}(\d+(?:[.,]\d+)?)", t or "", re.I)
        return float(m.group(1).replace(",", ".")) if m else None
    p_fact = after("фактическая", mk) if mk else num(val(r"Фактическая мощность устанавливаемого котла"))
    p_req = after("требуемая", mk) if mk else num(val(r"Требуемая мощность котла"))
    p = p_fact if p_fact is not None else p_req
    if p is None: return []
    L = []
    if p_req is not None and p_fact is not None:
        L.append(f"Теплотехнический расчёт объекта: требуемая мощность котла {fmt(p_req, 0)} кВт, "
                 f"фактическая мощность устанавливаемого котла {fmt(p_fact, 0)} кВт.")
    alloc = val(r"Выделенная мощность")
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*кВт\D{0,12}?(\d)\s*фаз", alloc, re.I)
    if not m:   # фазности и выделенной мощности нет (опросный лист не заполнен) — только ток котла в обоих вариантах
        return L + lines_for(p, 1) + lines_for(p, 3) + [NO_ALLOC]
    total, ph = float(m.group(1).replace(",", ".")), int(m.group(2))
    per = total / ph
    L.append(f"Выделенная мощность по опросному листу {fmt(total, 0)} кВт на {ph} фаз"
             f"{'у' if ph == 1 else 'ы'}: лимит на одну фазу {fmt(per)} кВт.")
    L += lines_for(p, 1)
    L.append(f"При однофазном подключении вся мощность котла {fmt(p, 0)} кВт идёт по одной фазе: это "
             + (f"больше лимита {fmt(per)} кВт на фазу на {fmt(p - per)} кВт." if p > per
                else f"в пределах лимита {fmt(per)} кВт на фазу, запас на фазе {fmt(per - p)} кВт."))
    L += lines_for(p, 3)
    L.append(f"При трёхфазном подключении котёл {fmt(p, 0)} кВт даёт {fmt(p / 3)} кВт и ток ≈ {fmt(current(p, 3))} А "
             f"на каждую фазу: это "
             + (f"больше лимита {fmt(per)} кВт на фазу на {fmt(p / 3 - per)} кВт." if p / 3 > per
                else f"в пределах лимита {fmt(per)} кВт на фазу, запас на фазе {fmt(per - p / 3)} кВт."))
    return L

if __name__ == "__main__":
    claim = ("Если у вас 15 кВт на трёх фазах, автомат 25А — это на грани, без запаса. Если вдруг одна фаза (220В) — он категорически "
             "не подходит, нужен минимум на 63А или 80А. Обязательно уточните, почему не поставили 32А для вводного.")
    for l in from_claim(claim): print(l)
    assert fmt(current(15, 3)) == "22,8" and rating(current(15, 3)) == 25 and fmt(power(32, 3)) == "21,1"
    assert rating(current(15, 1)) == 80 and fmt(current(15, 1)) == "68,2"
    # реальный кейс 15.10.2026 (ответ инженера): котёл 6 кВт, выделено 15 кВт на 3 фазы → 5 кВт на фазу
    OBJ = {"items": [{"позиция": "Выделенная мощность кВт и фазность", "описание": "15кВт, 3фазы"},
                     {"позиция": "Требуемая мощность котла, кВт", "описание": "5"},
                     {"позиция": "Фактическая мощность устанавливаемого котла, кВт", "описание": "6"}]}
    P = from_project(OBJ, "электрокотел идет только на 220 вольт или на 380 можно?")
    for l in P: print(l)
    assert "27,3 А" in P[2] and "9,1 А" in P[4] and "лимит на одну фазу 5,0 кВт" in P[1]
    assert "больше лимита 5,0 кВт на фазу на 1,0 кВт" in P[3] and "2,0 кВт и ток ≈ 9,1 А" in P[5]
    assert from_project(OBJ, "почему сайдинг виниловый") == []
    NO = from_project({"items": [{"позиция": "Мощность котла, кВт", "описание": "требуемая по расчёту 5, фактическая устанавливаемая 6"}]},
                      "электрокотел 220 или 380")
    assert NO[-1] == NO_ALLOC and not any("лимит" in l for l in NO[:-1])   # без опросного листа — ни слова о лимите фазы
    OBJ2 = {"items": [{"позиция": "Выделенная мощность кВт и фазность", "описание": "15кВт, 3фазы"},
                      {"позиция": "Мощность котла, кВт", "описание": "требуемая по расчёту 5, фактическая устанавливаемая 6"}]}
    assert from_project(OBJ2, "электрокотел 220 или 380") == P   # склеенная позиция читается так же
    print("проверки: ок")
