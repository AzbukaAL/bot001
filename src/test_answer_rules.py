# позиция инженера ДО и ПОСЛЕ дописанной 16.10 фразы Сергея Бердникова
SK_OLD = ("Мы ставим электрические котлы THERMEX модели Boss 12 Wi-Fi. Котёл имеет диапазон настроек от 2 до 12 кВт, кратно 2 кВт. "
          "Подключение котла может быть как трёхфазным, так и однофазным. При однофазном подключении есть ограничение 8 кВт. "
          "При однофазном подключении вся мощность котла идёт по одной фазе, и если она превышает лимит выделенной мощности "
          "на одну фазу, вводной автомат отключает дом, а запаса на бытовые приборы на этой фазе не остаётся.")
SK_NEW = SK_OLD.replace("При однофазном подключении есть ограничение 8 кВт.",
                        "При однофазном подключении есть ограничение 8 кВт. Котёл THERMEX Boss 12 Wi-Fi на трёх фазах "
                        "настраивается на 2, 4, 6, 8, 10, 12 кВт; на одной фазе — 2, 4, 6, 8 кВт.")
B = lambda q: [{"ref": "СК-ИНЖ §1.1", "label": "Стандарт компании", "quote": q, "standard": True, "client_ok": True, "mark": None}]
CALC = ["Выделенная мощность по опросному листу 15 кВт на 3 фазы: лимит на одну фазу 5,0 кВт.",
        "6 кВт, одна фаза (220 В), cos φ = 1: I = P / U = 6000 / 220 ≈ 27,3 А → ближайший стандартный номинал автомата 32 А.",
        "При однофазном подключении вся мощность котла 6 кВт идёт по одной фазе: это больше лимита 5,0 кВт на фазу на 1,0 кВт.",
        "При трёхфазном подключении котёл 6 кВт даёт 2,0 кВт и ток ≈ 9,1 А на каждую фазу: это в пределах лимита 5,0 кВт на фазу, запас на фазе 3,0 кВт."]
Q = "электрокотел идет только на 220 вольт или на 380 можно? И вообще нужна ли такая мощность ,в чем смысл этой истории."
ASSERT_CLAIM = "Однокамерный стеклопакет для Московского региона будет промерзать."

GOOD = {"conclusion": "Претензия не подтверждается",
        "short": "Котёл работает и от 220 В, и от 380 В, но для Вашего дома подходит только трёхфазное подключение [1][Р]",
        "reasoning": "При однофазном подключении есть ограничение 8 кВт [1]. Котёл 6 кВт на одной фазе дал бы ток 27,3 А, "
                     "а это больше лимита 5,0 кВт на фазу [Р]. При трёхфазном подключении те же 6 кВт дают 2,0 кВт "
                     "и ток 9,1 А на каждую фазу — в пределах лимита, с запасом 3,0 кВт [Р].",
        "action": None, "clarify": None}
NO_ARG = dict(GOOD, short="Котёл настроен на 6 кВт по теплотехническому расчёту [Р]",
              reasoning="При трёхфазном подключении 6 кВт распределяются по 2,0 кВт на фазу — в пределах выделенного [Р].")
PAIR_12 = dict(GOOD, short="Котёл работает и на 220 В (до 8 кВт), и на 380 В (до 12 кВт) [1]")
PAIR_10 = dict(GOOD, short="На 220 В котёл можно настроить до 10 кВт [1]")
CAUSE_CALC = dict(GOOD, reasoning=GOOD["reasoning"] + " Превышение лимита приведёт к срабатыванию вводного автомата [Р].")
CAUSE_QUOTE = dict(GOOD, reasoning=GOOD["reasoning"] + " Превышение лимита на одну фазу приведёт к тому, что вводной автомат "
                                                       "отключает дом, и запаса на бытовые приборы на фазе не остаётся [1].")
NA_ON_Q = dict(GOOD, conclusion=A.NOT_APPLICABLE, short=A.NOT_APPLICABLE)
chk = lambda w, q=SK_NEW, calc=CALC, claim=Q: A.check_facts(w, B(q), calc, claim)
has = lambda probs, txt: any(txt in p for _, p in probs)

good, no_arg = chk(GOOD), chk(NO_ARG)
pair_new, pair_old = chk(PAIR_12), chk(PAIR_12, SK_OLD)
pair10 = chk(PAIR_10)
cause_calc, cause_quote = chk(CAUSE_CALC), chk(CAUSE_QUOTE)
na, na_ok = chk(NA_ON_Q), chk(NA_ON_Q, claim=ASSERT_CLAIM)
no_over = chk(NO_ARG, calc=[CALC[0], CALC[3]])

checks = {
    "правильный ответ проходит все проверки": good == [],
    "довод про однофазное превышение обязателен — его отсутствие ловится": has(no_arg, "довод из расчёта обязателен"),
    "без строки превышения в расчёте довод не требуется": not has(no_over, "довод из расчёта обязателен"),
    "«380 В — до 12 кВт» проходит после дописанной фразы Сергея (16.10)": not has(pair_new, "12 кВт привязано"),
    "та же фраза отклонялась, пока привязки в позиции не было": has(pair_old, "12 кВт привязано"),
    "«220 В — до 10 кВт» отклоняется: 10 кВт перечислено только для трёх фаз": has(pair10, "10 кВт привязано"),
    "«220 В — до 8 кВт» не отклоняется (8 кВт есть для одной фазы)": not has(pair_new + good, "8 кВт привязано"),
    "«лимит на одну фазу 5,0 кВт» из расчёта проходит": not has(good, "5,0 кВт привязано"),
    "следствие «приведёт к» только с [Р] отклоняется": has(cause_calc, "причина или следствие без ссылки на цитату"),
    "следствие «приведёт к» со ссылкой на цитату проходит": cause_quote == [],
    "«не относится» на вопрос покупателя отклоняется": has(na, "вывод «не относится» неприменим"),
    "«не относится» на утверждение остаётся разрешённым": not has(na_ok, "не относится» неприменим"),
    "вопрос покупателя: утверждения нет, у претензии — есть":
        not A.has_assertion(Q) and A.has_assertion(ASSERT_CLAIM)
        and A.has_assertion("Автомат 25 А — на грани, без запаса. Почему не поставили 32 А?"),
}
for k, v in checks.items(): print(("✅ " if v else "❌ ") + k)
if not all(checks.values()):
    for name, pr in [("good", good), ("pair_new", pair_new), ("cause_calc", cause_calc), ("cause_quote", cause_quote)]:
        print(f"\n{name}:", " | ".join(p for _, p in pr) or "—")
sys.exit(0 if all(checks.values()) else 1)
