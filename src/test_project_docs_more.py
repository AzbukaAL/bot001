r = PD.windows("x.pdf", WIN); it = r["items"]
check("окна: вид определяется", PD.kind("x.pdf", WIN) == "спецификация окон")
check("окна: изделия с типом, размером, заполнением, количеством", [i["позиция"] for i in it] == ["Окна и двери: изделие 1 (дверь)", "Окна и двери: изделие 2 (окно)"]
      and "размер 602×1330 мм" in it[1]["описание"] and "4M1-12-4M1-8-4M1" in it[1]["описание"] and "2 шт." in it[1]["описание"])
obj = {"label": "Данные Вашего проекта", "items": [{"id": "X1", "позиция": "Утепление внешних стен", "описание": "Каменная вата 150 мм", "ocr": True,
       "источник_метка": "техническое описание от 23.03.2026"}, {"id": "X2", "позиция": "Окна", "описание": "профиль 70, 4M1-12", "ocr": False,
       "источник_метка": "спецификация окон"}]}
ob = A.object_basis("Утепление стен 150 мм мало", obj, k=2)
check("со скана: покупателю нет, пометка «скан — сверить»", ob and ob[0]["client_ok"] is False and ob[0]["mark"] == "скан — сверить с оригиналом")
check("с текстового слоя: как раньше", all(b["client_ok"] for b in A.object_basis("Окна профиль 70", obj, k=2) if b["ref"] == "X2"))
for f, k in (("materials/objects/test1-kp.pdf", "КП"), ("materials/objects/oprosnyi-list-kotel.pdf", "опросный лист"),
             ("materials/objects/teplotekh-raschet-kotel.pdf", "теплотехнический расчёт")):
    if os.path.exists(f"{ROOT}/{f}"): check(f"прежний вид не сдвинулся: {k}", PD.kind(f"{ROOT}/{f}") == k)
D = f"{ROOT}/materials/objects/52r5"
if os.path.isdir(D):
    fs = [f for f in sorted(glob.glob(D + "/*.pdf")) if re.search(r"ТО|[Сс]мета|окна", os.path.basename(f))]
    obj, docs = PD.build_docs(fs)
    check("52Р5: три вида распознаны", sorted(d["kind"] for d in docs) == ["смета", "спецификация окон", "техническое описание"])
    check("52Р5: позиции есть, со сканов помечены", obj and all(d["items"] > 0 for d in docs) and all(i["ocr"] == (d_["ocr"]) for d_ in docs for i in obj["items"] if i["источник_метка"].startswith(d_["kind"])))
    check("52Р5: в позициях нет меток ПДн", "<" not in json.dumps(obj["items"], ensure_ascii=False) and not anonymize(json.dumps(obj["items"], ensure_ascii=False))[1])
print(f"новые виды данных проекта: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
