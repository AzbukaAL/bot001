import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import answer as A

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)

Q74 = ("По желанию заказчика базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом. "
       "Такое решение особенно рекомендуется для домов постоянного проживания и регионов с холодным климатом.")
Q75 = "Терморазрыв уменьшает передачу холода через металлические элементы полотна и коробки."
B = [{"label": "СК", "quote": Q75, "standard": True}, {"label": "СК", "quote": Q74, "standard": True}]
live = ("Базовая дверь имеет ограничения по теплозащите; по желанию заказчика базовая дверь может быть заменена на улучшенную "
        "металлическую дверь с терморазрывом [2].")
pr = A.product_problems({"reasoning": live}, B)
check("живой случай 20.10: часть из §7.4 не ловится", not any(p[0].lower().startswith("по желанию") for p in pr))
check("живой случай: часть без основания по-прежнему ловится", any(p[0].startswith("Базовая дверь имеет ограничения") for p in pr))
check("дословно, без ссылки, с другим регистром и пунктуацией", not A.product_problems(
    {"short": "По желанию заказчика — базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом"}, B))
check("почти дословно (одно слово выпало)", not A.product_problems(
    {"reasoning": "По желанию заказчика базовая дверь может быть заменена на улучшенную дверь с терморазрывом."}, B))
check("отрицание, которого нет в цитате, — ловится", A.product_problems(
    {"reasoning": "По желанию заказчика базовая дверь не может быть заменена на улучшенную металлическую дверь с терморазрывом."}, B))
check("перекрытие слов, но не цитата — ловится", A.product_problems(
    {"reasoning": "Базовая дверь подобрана с учётом холодного климата и постоянного проживания."}, B))
check("цитата из основания ДРУГОГО пункта не засчитывается", A.product_problems(
    {"reasoning": "По желанию заказчика базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом."}, B[:1]))
check("отсутствие свойства: дословно из цитаты — проходит", not A.absence_problems(
    {"reasoning": "Дополнительного замка, ночной задвижки и эксцентрика нет."},
    [{"label": "СК", "quote": "Замок: цилиндровый НТО ЛУЧ; дополнительного замка, ночной задвижки и эксцентрика нет. Ручка на планке."}]))
