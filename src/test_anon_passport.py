"""Обезличиватель: паспорт (21.10.2026, п. 8.3) — серия и номер, «выдан …», код подразделения, дата выдачи; ловушки — нет.
Данные в тесте выдуманные.  python3 src/test_anon_passport.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from anonymize import anonymize

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)
def tags(t): return re.findall(r"<([А-ЯA-Z]+)_\d+>", anonymize(t)[0])
def left(t): return anonymize(t)[0]

POS = [("паспорт 60 12 345678", "345678"), ("Паспорт: 6012345678", "6012345678"), ("серия 60 12 № 345678", "345678"),
       ("паспорт РФ серия 6012 номер 345678", "345678"), ("данные: 60 12 345678, выдан", "345678"),
       ("выдан ГУ МВД России по Ростовской обл. 01.02.2015, код подразделения 610-001", "МВД"),
       ("Выдан отделом УФМС 15.03.2011 г.", "УФМС"), ("код подразделения 610-001", "610-001"), ("дата выдачи 01.02.2015", "01.02.2015"),
       ("выдан ОВД района, код 610-002", "610-002")]
for t, secret in POS:
    check(f"маскируется: {t}", "ПАСПОРТ" in tags(t) and secret not in left(t))
NEG = ["см. п. 6.2.16 СП 60.13330.2020", "размер дома 6000х9000 мм", "стоимость 1 245 000 руб.", "итого 3 456 789,00",
       "ГОСТ 24866-2014", "ГОСТ 30331.5-95", "СП 17.13330.2017", "договор от 12.10.2026", "приложение № 11 от 01.09.2026",
       "ИНН 6165123456", "артикул 6012345678", "брус 150х150, шаг 600", "лист 1250х2500х12", "пункт 4.2.3"]
for t in NEG:
    check(f"НЕ паспорт: {t}", "ПАСПОРТ" not in tags(t) and left(t) == t if "ИНН" not in t else "ПАСПОРТ" not in tags(t))
ADDR = [("расположенного по адресу: Ростовская обл, р-н Каменский, г Каменск, сад Ромашка, участок 5", "Ромашка"),
        ("кадастровый номер 61:54:0500301:80", "0500301"), ("участок 61:54:0500301:80 под ИЖС", "0500301"),
        ("Адрес: 346130, Ростовская обл., г. Миллерово", "346130"),
        ("Адрес регистрации: Ростовская область, г Каменск ул.", "Каменск"), ("адрес проживания: г. Каменск, Лесная", "Лесная")]
for t, secret in ADDR: check(f"адрес/кадастр: {t[:40]}", "АДРЕС" in tags(t) and secret not in left(t))
for t in ("Адрес объекта в КП не указан.", "по проекту Барн-хаус 2эт.", "время 12:30:45", "масштаб 1:100", "п. 4.2.3 СП 50"):
    check(f"НЕ адрес: {t}", "АДРЕС" not in tags(t))
check("телефон — по-прежнему ТЕЛ", tags("тел. +7 988 111-22-33") == ["ТЕЛ"])
check("адрес — по-прежнему АДРЕС", "АДРЕС" in tags("ул. Ленина д. 5 кв. 7"))
check("ФИО с инициалом — по-прежнему", "ФИО" in tags("Договор подписал И. Зайцев."))
check("Алексей Самсонов — как прежде", tags("Алексей Самсонов") == [])
print(f"паспорт: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
