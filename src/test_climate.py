"""wip/sp131-climate (27.10.2026): таблицы СП 131.13330.2025 построчно, ГСОП и требуемое R по СП 50 — кодом, не моделью.
python3 src/test_climate.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import climate_sp131 as CL, calc_teplo as CT

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)

# а) значения из таблицы 5.1 — код, не модель (Ростов-на-Дону и Миллерово — требование задания; Луганск — объект эталона)
for name, t5_098, t5_092, z8, t8, z10, t10 in [("Ростов-на-Дону", -21, -18, 164, 0.3, 180, 1.1),
                                               ("Миллерово", -23, -21, 178, -1.2, 193, -0.4),
                                               ("Луганск", -26, -23, 173, 0.1, 191, 0.9)]:
    p = CL.lookup(name); c = (p or {}).get("cold") or {}
    check(f"{name}: пятидневка 0,98/0,92", c.get("t_5day_098") == t5_098 and c.get("t_5day_092") == t5_092)
    check(f"{name}: период ≤8 °C", c.get("z_le8") == z8 and c.get("t_le8") == t8)
    check(f"{name}: период ≤10 °C", c.get("z_le10") == z10 and c.get("t_le10") == t10)
    check(f"{name}: сверено с копией Минстроя", bool(p and p["checked"]))
    check(f"{name}: тёплый период и месячные есть", bool(p and p.get("warm") and p.get("monthly")))
p = CL.lookup("ростов-на-дону"); check("регистр имени не важен", bool(p) and p["region"] == "Ростовская область")
check("Ростов-на-Дону: тёплый период 0,95/0,98", p["warm"]["t_095"] == 28 and p["warm"]["t_098"] == 30 and p["warm"]["pressure_hPa"] == 1008)
check("Ростов-на-Дону: январь и год", p["monthly"]["I"] == -3.5 and p["monthly"]["год"] == 10.1)
check("нет такого пункта → None", CL.lookup("Нарния") is None and CL.lookup("") is None)
check("строка пункта для индекса", "наиболее холодной пятидневки обеспеченностью 0,98, °C — -21; то же, обеспеченностью 0,92, °C — -18" in CL.point_text("Ростов-на-Дону", p))

# б) разбор строк: переносы имени в обеих копиях, двойное направление ветра, латинская C, номер страницы, сноска
cols = [(f"c{i}", f"c{i}") for i in range(3)]
T = ("Таблица 9.9 - проба\n\nРостовская область\n\nКомсомольск-на-        -25   87   В\nАмуре\n\n"
     "Александровск-Сахалински   -31   165   З\nй\n\nПетропавловск-\n                       -21   156   C\nКамчатский\n\n"
     "Александровский    -40   188   CЗ\n                                   57\nХерсон     -23   68   З, СЗ\nОрел   -27*   128*   Ю\n"
     "   * Вероятно, ошибка оригинала.\nСломанная строка   -9,8   -4,\n\nТаблица 10.1 - дальше\nЧужой   1   2   3\n")
rows, probs = CL.parse_table(T, "9.9", cols)
check("перенос после чисел (заказчик)", "Комсомольск-на-Амуре" in rows and rows["Комсомольск-на-Амуре"][1]["c0"] == -25)
check("однобуквенный хвост без пробела", "Александровск-Сахалинский" in rows)
check("имя на своей строке, числа ниже (Минстрой)", rows.get("Петропавловск-Камчатский", (0, {}))[1].get("c2") == "С")
check("латинская C → кириллица", rows["Александровский"][1]["c2"] == "СЗ")
check("номер страницы — не перенос имени", "Александровский 57" not in rows and "Александровский" in rows)
check("«З, СЗ» — одна ячейка", rows["Херсон"][1]["c2"] == "З,СЗ")
check("сноска: звёздочка снята, пометка есть", rows["Орел"][1]["c0"] == -27 and rows["Орел"][2] is True)
check("регион подхвачен", rows["Херсон"][0] == "Ростовская область")
check("неполная строка — в проблемы, не в данные", "Сломанная строка" not in rows and any("Сломанная строка" in x for x in probs))
check("следующая таблица не читается", "Чужой" not in rows)
check("таблицы нет → явная проблема", CL.parse_table("ничего", "5.1", cols) == ({}, ["таблица 5.1 не найдена"]))

# в) сверка: 2 копии свода дали одно и то же почти по всем пунктам; расхождения помечены, а не замяты
D = CL.data()
check("пунктов в таблицах ≥ 540", len(D) >= 540)
check("сверено ≥ 98 %", sum(d["checked"] for d in D.values()) >= 0.98 * len(D))
check("Донецк: расхождение копий помечено", D.get("Донецк", {}).get("checked") is False and any("расходится" in n for n in D["Донецк"]["notes"]))

# г) ГСОП и требуемое R — формула 5.2 и таблица 3 СП 50 из текста свода
t3 = CT.table3()
check("таблица 3: a, b стен/покрытий/перекрытий", t3["a"][:3] == [0.00035, 0.0005, 0.00045] and t3["b"][:3] == [1.4, 2.2, 1.9])
check("таблица 3: окна по строкам", [r[4] for r in t3["rows"]] == [0.49, 0.49, 0.63, 0.73, 0.75, 0.77, 0.8])
g = CT.gsop(0.3, 164); R = CT.r_req(g)
check("Ростов: ГСОП 3231", CT.fmt(g, 0) == "3231")
check("Ростов: R стен 2,53", CT.fmt(R["стены"]["value"]) == "2,53")
check("Ростов: R перекрытий 3,35", CT.fmt(R["перекрытия чердачные и полы над подпольем"]["value"]) == "3,35")
check("Ростов: R окон 0,58 (интерполяция)", CT.fmt(R["окна"]["value"]) == "0,58" and "интерполяция" in R["окна"]["how"])
g = CT.gsop(-1.2, 178); check("Миллерово: ГСОП 3774, R стен 2,72", CT.fmt(g, 0) == "3774" and CT.fmt(CT.r_req(g)["стены"]["value"]) == "2,72")
check("граница таблицы: 12000 → 0,8", CT.fmt(CT.r_req(12000)["окна"]["value"]) == "0,80" and CT.fmt(CT.r_req(20000)["окна"]["value"]) == "0,80")

# д) по данным проекта (теплотехнический расчёт заказчика: Луганск, расчётная температура −23)
OBJ = {"items": [{"позиция": "Город (место строительства)", "описание": "Луганск"},
                 {"позиция": "Расчётная температура наружного воздуха, °C", "описание": "-23"}]}
L = CT.from_project(OBJ, "утепление стен 150 мм для Луганска недостаточно")
check("Луганск: строка таблицы", L and "Луганск" in L[0] and "-23 °C" in L[0] and "173 сут" in L[0] and "0,1 °C" in L[0])
check("Луганск: расчётная температура совпала с таблицей", "совпадает с таблицей 5.1" in L[1])
check("Луганск: ГСОП 3443", any("= 3443 °C·сут" in l for l in L))
check("Луганск: R стен 2,60, перекрытий 3,45, окон 0,59", any("стены — 0,00035·3443 + 1,4 = 2,60" in l and "= 3,45" in l and "= 0,59" in l for l in L))
check("фактическое R не считаем — сказано явно", L[-1] == CT.NO_LAMBDA)
OBJ2 = {"items": [{"позиция": "Город (место строительства)", "описание": "Луганск"}, {"позиция": "Расчётная температура наружного воздуха, °C", "описание": "-19"}]}
check("расчётная температура не та — сказано явно", any("НЕ совпадает (в таблице -23 °C)" in l for l in CT.from_project(OBJ2, "теплопотери")))
check("город не из таблицы — явная строка", CT.from_project({"items": [{"позиция": "Город (место строительства)", "описание": "Нарния"}]}, "утепление")[0].startswith("Место строительства по теплотехническому расчёту объекта — Нарния: в таблице 5.1"))
check("не теплотехника → пусто", CT.from_project(OBJ, "автомат 25 А мал") == [] and CT.from_project(None, "утепление") == [])
check("нет города → пусто", CT.from_project({"items": [{"позиция": "Утеплитель стен, мм", "описание": "150"}]}, "утепление") == [])

print(f"климат и теплотехника: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
