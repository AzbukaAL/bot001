"""Утверждение об отсутствии свойства у изделия / базовой комплектации (19.10.2026, решение Вадима, вариант 3): только если
в основании это прямо сказано. Фразы — из ответов K061 по ветке wip/door-base.  python3 src/test_absence.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import answer as A

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)

Q75 = ("Терморазрыв уменьшает передачу холода через металлические элементы полотна и коробки и позволяет снизить вероятность сильного "
       "охлаждения внутренних поверхностей двери и образования конденсата. При выборе наружной двери учитывается не только наличие "
       "терморазрыва, но и характеристики дверного блока в целом: конструкция полотна и коробки, утепление, количество контуров уплотнения.")
Q21 = ("Базовая входная дверь: модель Стройгост, антик медь / рустикальный дуб, металл–панель. Толщина полотна 45 мм, толщина короба 52 мм, "
       "короб открытый. Наполнитель: пенополистирол (ППС). Контуры уплотнения: 1 контур, вспененная резина.")
Q74 = "По желанию заказчика базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом."
SK = [{"label": "СК", "quote": q, "standard": True} for q in (Q75, Q21, Q74)]
KP = [{"label": "Данные Вашего проекта (КП)", "quote": "Двери входные: с термо разрывом, утепление (50+29) мм", "object": True}] + SK
def hit(text, basis=SK, field="reasoning"): return bool(A.absence_problems({field: text}, basis))

K061_1 = ("Базовая дверь имеет утепление пенополистиролом, толщину полотна 45 мм и контур уплотнения [1][2], но терморазрыва в ней нет — "
          "для холодного климата мы предлагаем улучшенную дверь с терморазрывом как опцию [3]")
K061_2 = ("Однако отсутствие терморазрыва действительно увеличивает передачу холода через металлические элементы и вероятность "
          "охлаждения внутренних поверхностей двери [1].")
check("K061: «терморазрыва в ней нет» ловится", hit(K061_1, field="short"))
check("K061: «отсутствие терморазрыва» ловится", hit(K061_2))
check("КП: «в Вашем КП указана дверь с терморазрывом» — нет", not hit("В Вашем КП указана дверь с терморазрывом [1].", KP))
check("КП: сравнение «без терморазрыва» с проектом — исключение", not hit("Претензия о двери без терморазрыва не соответствует данным Вашего проекта [1].", KP))
check("основание прямо говорит — проходит", not hit("В базовой двери терморазрыва нет [1].", [{"label": "СК", "quote": "Базовая дверь поставляется без терморазрыва."}]))
check("норма: «в нормах нет требования к двери» — не проверяется", not hit("В нормах нет требования к терморазрыву входной двери."))
check("слова покупателя: «Вы пишете о двери без терморазрыва»", not hit("Вы пишете о двери без терморазрыва."))
check("цитата покупателя в кавычках", not hit("Ваше опасение «дверь без терморазрыва промерзнет» понятно."))
check("оговорка «без этих данных»", not hit("Без этих данных о кровле нельзя оценить крепление."))
check("не о продукте: «вопросов нет»", not hit("Других вопросов нет."))
check("о документах: «в стандартах нет данных о фасаде»", not hit("В наших стандартах нет данных о ветровых нагрузках для фасада."))
check("«То есть именно то, что Вы предлагаете» — нет", not hit("То есть именно то, что Вы предлагаете."))
FULL21 = [{"label": "СК", "quote": Q21 + " Замок: цилиндровый НТО ЛУЧ; дополнительного замка, ночной задвижки и эксцентрика нет."}]
check("раздел прямо говорит «ночной задвижки нет» — проходит", not hit("В базовой двери нет ночной задвижки [1].", FULL21))
check("в основаниях этого нет — ловится", hit("В базовой двери нет ночной задвижки [2].", SK))
check("причина инженеру", A.facts_why([("x", A.ABSENCE_WHY + " — убери")]) == A.ABSENCE_WHY)

# маршрут целиком (модель подменена)
orig = (A.analyze, A.select_basis, A.write, A.judge)
A.analyze = lambda c, obj=None: {"claim": c, "mapping": {}, "verdict": 2, "status": "ok", "direct": "СК-ЧБ §7.4", "evidence": "", "cite": [], "reason": "",
                       "counter_question": None, "usage": {}, "raw_verdict": 2, "norm_ids": [], "sk_ids": []}
A.select_basis = lambda a: ([dict(b, ref=f"СК-X §{k}", label_engineer="СК", client_ok=True, mark=None) for k, b in enumerate(SK, 1)], [], {})
BAD = {"conclusion": "Претензия подтверждается частично", "short": "Дверь с терморазрывом доступна как опция [3].",
       "reasoning": K061_2 + " По желанию заказчика базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом [3].",
       "action": None, "clarify": None}
GOOD = dict(BAD, reasoning="По желанию заказчика базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом [3].")
seq, MODE = [], ["good"]
A.write = lambda *a, **k: (seq.append(1), (dict(BAD) if len(seq) == 1 or MODE[0] == "bad" else dict(GOOD), {}))[1]
A.judge = lambda *a, **k: ({"stance": "за покупателя", "addresses": True, "formal": False}, {})
o, _ = A.answer("Входная дверь КНР без терморазрыва — это плохое решение")
check("переписано: покупателю, без «отсутствие терморазрыва»", o["route"] == "client" and len(seq) == 2 and "отсутствие" not in (o.get("reasoning") or ""))
MODE[0] = "bad"; seq.clear(); o, _ = A.answer("Входная дверь КНР без терморазрыва — это плохое решение")
check("не переписалось: инженеру с причиной", o["route"] == "engineer" and o["internal"]["engineer_why"] == A.ABSENCE_WHY)
A.analyze, A.select_basis, A.write, A.judge = orig
print(f"утверждение об отсутствии свойства: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
