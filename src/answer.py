    ids = [r for r in norm if source_text(r)] + [r for r in a["sk_ids"][:4] if source_text(r)]
    if not ids: return [], [], {}
    keys = {f"F{k}": r for k, r in enumerate(ids, 1)}
    frag = "\n".join(f"[{k}] ({'НОРМА ' + label(r) if not r.startswith('СК-') else 'СТАНДАРТ КОМПАНИИ'}) {source_text(r)[:900]}" for k, r in keys.items())
    vt = {1: "претензия подтверждается", 2: "претензия не подтверждается", 3: "для ответа нужны данные"}.get(a["raw_verdict"], "не определён")
