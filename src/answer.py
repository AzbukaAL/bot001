def object_basis(claim, obj, k=2):
    """Данные проекта покупателя (КП, src/object_index.py → build): позиции, ближе всего к претензии (+ электрика для электрики)."""
    if not obj: return []
    cs = set(stems(claim)) - GLUE; el = bool(ELECTRIC.search(claim))
    topics = [it for cr, it in KP_TOPICS if re.search(cr, claim, re.I)]
    def score(i):
        t = f"{i['позиция']} {i['описание']}"
        return len(cs & set(stems(t))) + (3 if el and re.search(r"электр", t, re.I) else 0) + \
               (5 if any(re.search(it, i["позиция"], re.I) for it in topics) else 0)
    items = [i for i in obj["items"] if (i.get("описание") or "").strip() and score(i) > 0]
    best = sorted(items, key=score, reverse=True)[:k]
    on_topic = lambda i: any(re.search(it, i["позиция"], re.I) for it in topics)
    best = best[:1] + [i for i in best[1:] if (on_topic(i) if topics else score(i) >= 2)]   # вторая позиция — только по теме претензии
    # 15.10: у каждой позиции свой источник — КП, опросный лист или теплотехнический расчёт, с датой документа
    src = lambda i: f"Данные Вашего проекта ({i['источник_метка']})" if i.get("источник_метка") else obj["label"]
    return [{"ref": i["id"], "label": f"{src(i)}: {i['позиция']}", "label_engineer": f"{src(i)}: {i['позиция']}",
             "quote": f"{i['позиция']}: {i['описание']}", "standard": False, "client_ok": not i.get("ocr"),   # 21.10: со скана —
             "mark": SCAN_MARK if i.get("ocr") else None, "object": True} for i in best]   # покупателю без сверки нет

