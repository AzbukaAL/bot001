    if w == "формально": return f"ответ формально снимает опасение покупателя («{a.get('fear')}») ссылкой на норму — по существу не отвечает"
    if w.startswith("нет основания"): return internal.get("no_basis_human") or "нет основания, которое можно дать покупателю"
    if a["verdict"] == 4: return "система относит вопрос к зоне ответственности не компании, но подтверждающей цитаты нет"
    if a["verdict"] == 5: return "основание не найдено ни в нормах, ни в стандарте компании"
    return "система не смогла определить вердикт"

