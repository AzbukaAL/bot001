    internal = {"verdict": None, "raw_verdict": None, "status": "пустой поиск", "fear": fear_of(claim), "empty_search": True,
                "engineer_why": "пустой поиск", "found": [],
                "why_human": f"{EMPTY_SEARCH} — модель не вызывалась; в пункте нет сути замечания или его слов нет в нормах"}
