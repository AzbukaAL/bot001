class ModelError(Exception):
    """17.10: П-5/П-7 — модель недоступна или её ответ не разобрать (сеть, HTTP-ошибка — в т. ч. снятая модель, ответ без choices)."""

def chat(system, user, max_tokens=700, *, role):
    model = llm_roles.model(role); t0 = time.time()
    step = {SELECT_SYS: "select", WRITE_SYS: "write", JUDGE_SYS: "judge"}.get(system, "other")
    body = {"model": model, "max_tokens": max_tokens, "temperature": 0,
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}]}
    req = urllib.request.Request("https://polza.ai/api/v1/chat/completions", data=json.dumps(body).encode(), method="POST",
                                 headers={"Authorization": "Bearer " + R8.KEY, "Content-Type": "application/json"})
    try:
        with urlopen_retry(req, 120, on_error=lambda e: log_call(step, role, model, system, t0, {}, e)) as r: d = json.load(r)
        txt = d["choices"][0]["message"]["content"]
    except OSError as e:   # сеть и HTTP — в журнале уже есть (on_error)
        raise ModelError(f"{step}: {type(e).__name__}{' ' + str(e.code) if hasattr(e, 'code') else ''}") from e
    except (ValueError, KeyError, IndexError, TypeError) as e:   # ответ пришёл, но не тот
        log_call(step, role, model, system, t0, {}, e); raise ModelError(f"{step}: ответ без текста ({type(e).__name__})") from e
    log_call(step, role, model, system, t0, d.get("usage", {}))
    USAGE.append(d.get("usage", {}))
    return txt, d.get("usage", {})

