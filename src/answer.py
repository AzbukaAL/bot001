        try: return urllib.request.urlopen(req, timeout=timeout)
        except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
            if on_error: on_error(e)   # 17.10: П-12 — неудачная попытка тоже в журнал
            if n == tries - 1 or (isinstance(e, urllib.error.HTTPError) and e.code not in (408, 409, 425, 429, 500, 502, 503, 504)): raise
            time.sleep(3 * (n + 1))

