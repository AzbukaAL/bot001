def norm_ws(t): return " ".join((t or "").replace("­", "").split())
PAGE_HEAD = re.compile(r"\s\d{1,3}\s+СП\s+\d[\d.]+(?=\s)")   # колонтитул страницы внутри текста пункта («54 СП 256.1325800.2016»)

def full_sentence_quote(src, quote, max_len=650):
    """Цитата дословно из источника (без учёта регистра и пробелов), расширенная до границ предложений. None — не нашлась."""
    S = R8.unhyph(PAGE_HEAD.sub("", norm_ws(src))); q = R8.unhyph(PAGE_HEAD.sub("", norm_ws(quote))).strip(" «»\"'….")   # 17.10: перенос строки
    if len(q) < 15: return None
    i = S.lower().find(q.lower())
    if i < 0:   # модель вставила многоточие или чуть изменила конец — ищем самую длинную дословную часть ≥ 40 символов
        parts = sorted((x.strip(" «»\"'.,;") for x in re.split(r"…|\.\.\.", q)), key=len, reverse=True)
        parts += [q[:80], q[-80:]]
        hit = next((x for x in parts if len(x) >= 40 and S.lower().find(x.lower()) >= 0), None)
        if not hit: return None
        q = hit; i = S.lower().find(q.lower())
    j = i + len(q)
    st = max((m.end() for m in re.finditer(r"[.!?;:]\s+(?=[А-ЯЁA-Z«(\d•-])", S[:i])), default=0)
    m = re.search(r"[.!?;](?=\s+[А-ЯЁA-Z«(\d•-]|\s*$)", S[j - 1:])
    en = (j - 1 + m.end()) if m else len(S)
    out = S[st:en].strip()
    if len(out) > max_len:   # длинный абзац — от начала предложения с цитатой до конца предложения, где она кончается
        out = S[max(st, i - 200):en].strip()
    return out

SEG = re.compile(r"(?<=[.!?;:])\s+(?=[А-ЯЁA-Z«(\d•-])")

def trim_quote(ref, quote, model_quote, claim, limit=420):
    """Длинную цитату (весь абзац или перечень) — до 1–2 предложений/пунктов перечня: тех, где начало цитаты модели, и самых
    близких к претензии; у вручную сверенных пунктов — только внутри сверенного фрагмента."""
    v = VERIFIED.get(ref)
    if v and norm_ws(v["allowed"]).lower() in norm_ws(quote).lower(): return norm_ws(v["allowed"])
    if len(quote) <= limit: return quote
    segs = [x for x in SEG.split(quote) if x.strip()]
    mq = norm_ws(model_quote).lower()[:60]
    cs = set(stems(claim))
    score = lambda x: (3 if mq and mq[:40] in x.lower() else 0) + (2 if re.search(r"исключени|не распространя|допуска", x, re.I) else 0) + \
                      len(cs & set(stems(x))) / 10
    best = sorted(range(len(segs)), key=lambda k: -score(segs[k]))[:2]
    out = " ".join(segs[k] for k in sorted(best)).strip()
    return out if len(out) <= limit + 250 else segs[best[0]]

def client_usable(ref, quote):
    """Можно ли дать цитату покупателю: не скан и не «сверить», кроме вручную сверенных частей."""
    if ref.startswith("СК-"): return True, None
    hold = R8.OCR.get(ref)
    if not hold: return True, None
    v = VERIFIED.get(ref)
    if v and norm_ws(quote).lower().strip(" .") in norm_ws(v["allowed"]).lower(): return True, None
    return False, ("скан (OCR) — сверить с оригиналом" if hold == "распознано OCR" else f"сверить: {hold}")

