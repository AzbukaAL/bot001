def renumber(o, keys=("short", "reasoning", "action", "clarify")):
    """Ссылки [n] — по порядку первого появления (коротко → рассуждение → что делаем → уточнить); список оснований — в том же порядке."""
    basis = o.get("basis") or []
    order = []
    for k in keys:
        for x in re.findall(r"\[(\d+)\]", str(o.get(k) or "")):
            n = int(x)
            if 1 <= n <= len(basis) and n not in order: order.append(n)
    order += [n for n in range(1, len(basis) + 1) if n not in order]
    new = {old: i for i, old in enumerate(order, 1)}
    for k in keys:
        if o.get(k): o[k] = re.sub(r"\[(\d+)\]", lambda m: f"[{new.get(int(m.group(1)), int(m.group(1)))}]", o[k])
    o["basis"] = [basis[n - 1] for n in order]

def split_claims(text):
    """Несколько пунктов списком («1. …», «1) …», «- …», «• …») → список претензий; иначе одна."""
    parts = re.split(r"(?m)^\s*(?:\d{1,2}[.)]|[-•–])\s+", text.strip())
    parts = [" ".join(p.split()) for p in parts if p.strip()]
    return parts if len(parts) > 1 else [" ".join(text.split())]
