def na_short(w, basis, claim):
    """17.10: вывод «Замечание к Вашему проекту не относится» — короткий ответ кодом (решение Вадима 17.10): из рассуждения
    остаются только фразы со ссылкой на данные проекта (что заложено), плюс «То есть именно то, что Вы предлагаете», если в
    замечании есть предложение покупателя или модель сама так написала. Объяснения «почему/за счёт» не добавляем: модель писала
    их без ссылки, и правило CAUSAL (16.10) уводило стеклопакет с КП инженеру."""
    keep = [x for x in sentences(w.get("reasoning") or "")
            if any(1 <= int(n) <= len(basis) and basis[int(n) - 1].get("object") for n in re.findall(r"\[(\d+)\]", x))]
    if not keep: return w   # ссылки на данные проекта нет — оставляем как есть, дальше решают проверки
    same = PROPOSAL.search(claim) or "именно то, что Вы предлагаете" in (w.get("reasoning") or "")
    keep = [x for x in keep if "именно то, что Вы предлагаете" not in x]
    return dict(w, reasoning=" ".join(keep) + (" " + SAME_AS_PROPOSED if same else ""), action=None, clarify=None)

