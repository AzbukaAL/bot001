def _answer(claim_raw, obj=None):
    """Претензия → {route: client|engineer, conclusion, reasoning, action, clarify, basis, calc, internal:{…}}."""
    a = analyze(claim_raw, obj); usage = [a.pop("usage")]
    a["fear"] = fear_of(a["claim"])
    v = a["verdict"] if a["status"] == "ok" else None
    rv = a["raw_verdict"] if a["raw_verdict"] in (1, 2, 3) else None
    internal = {"verdict": a["verdict"], "raw_verdict": a["raw_verdict"], "status": a["status"], "direct": a["direct"], "reason": a["reason"],
                "fear": a["fear"]}
    out = {"claim": a["claim"], "mapping": a["mapping"], "internal": internal, "route": "engineer",
           "conclusion": None, "short": None, "reasoning": None, "action": None, "clarify": None, "basis": [], "calc": []}
    basis, rejected, u = select_basis(a); usage.append(u)
    internal["basis_all"] = basis; internal["basis_rejected"] = rejected
    calc = CE.from_claim(a["claim"]) or CE.from_project(obj, a["claim"]) or CT.from_project(obj, a["claim"]); out["calc"] = calc   # 15.10: числа из данных проекта
    E125 = "СП 256.1325800.2016|п.12.5"
    if calc and E125 in VERIFIED and not any(b["ref"] == E125 for b in basis):
        # 09.10: при расчёте электрики правило выбора номинала по расчётной нагрузке — всегда в основаниях (сверенная первая фраза;
        # без него модель называла больший номинал «запасом» — обратно позиции инженера P9–10)
        basis = [{"ref": E125, "label": label(E125), "label_engineer": label_engineer(E125), "quote": norm_ws(VERIFIED[E125]["allowed"]),
                  "standard": False, "client_ok": True, "mark": None}] + basis[:1]
        internal["basis_all"] = basis
    ob = object_basis(a["claim"], obj, k=3 if len((obj or {}).get("docs") or []) > 1 else 2)
    if ob: basis = ob + basis[:2]; internal["basis_all"] = basis; internal["object"] = obj["label"]
    if a.get("fear"):
        opts = [o for o in option_basis(a["claim"]) if not any(b["ref"] == o["ref"] and o["quote"] in b["quote"] for b in basis)]
        if opts: basis = basis[:1] + opts; internal["basis_all"] = basis
    client_basis = [b for b in basis if b["client_ok"]]
    # 16.10: «не относится» — только когда в пункте есть утверждение, которому можно не относиться
    conclusions = CONCLUSIONS.get(v or rv, ["Для ответа нужны данные"]) + \
                  ([NOT_APPLICABLE] if ob and has_assertion(a["claim"]) else [])
    # 21.10 (решение Вадима): данные проекта со скана — в основания для рассуждения и в черновик инженеру (с пометкой
    # «скан — сверить»), покупателю — нет: ссылка на них в тексте уводит пункт инженеру (ниже). Раньше при вердикте 1/2
    # они выпадали вовсе (52Р5: «каменная вата 150 мм» из ТО не попала ни в один ответ)
    scan = [b for b in basis if b.get("object") and b.get("mark") == SCAN_MARK]
