def option_basis(claim, k=8):
    """Решение против последствия в стандарте компании: опция/замена/улучшенный вариант (+ поясняющая фраза следом)."""
    out = []
    for r in R8.reg_candidates(claim, k=k):
        t = norm_ws(source_text(r)); sents = re.split(r"(?<=[.!?])\s+(?=[А-ЯЁA-Z«])", t)
        for n, x in enumerate(sents):
            if OPTION.search(x) and set(stems(x)) & set(stems(claim)) - GLUE:
                q = x + (" " + sents[n + 1] if n + 1 < len(sents) and re.match(r"(Такое|Это|Данное|Этот)\b", sents[n + 1]) else "")
                out.append({"ref": r, "label": label(r), "label_engineer": label_engineer(r), "quote": q, "standard": True,
                            "client_ok": True, "mark": None, "option": True})
                break
        if out: break
    return out

