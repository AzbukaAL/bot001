NUM_PROB = re.compile(r"^(число \S+ — нет|ограничение \S+ кВт привязано)")

def check_facts(w, basis, calc, claim):
    """17.10: П-9 — счётчик проблем с числами на каждой проверке; сама проверка — _check_facts."""
    probs = _check_facts(w, basis, calc, claim)
    NUMS.append(sum(1 for _, p in probs if NUM_PROB.match(p)))
    PRODS.append(sum(1 for _, p in probs if p.startswith(PRODUCT_WHY)))
    return probs

def trace(sec):
    """Трасса пункта (П-9): вызовы модели по шагам, попытки, токены, ₽ (cost_rub Polza), длительность, числа."""
    return {"code": CODE, "sec": round(sec, 1), "calls": list(TRACE), "attempts": dict(collections.Counter(e["step"] for e in TRACE)),
            "failed": sum(e["status"] == "failed" for e in TRACE), "tokens_in": sum(e["tin"] for e in TRACE),
            "tokens_out": sum(e["tout"] for e in TRACE), "rub": round(sum(e["rub"] for e in TRACE), 2),
            "models": sorted({e["model"] for e in TRACE}), "prompts": {e["step"]: e["prompt"] for e in TRACE},
            "numbers": {"checks": len(NUMS), "rewritten": sum(NUMS[:-1]), "to_engineer": NUMS[-1] if NUMS else 0},
            "style": style(),   # 21.10: тон и ирония, с которыми писался ответ
            "product": {"checks": len(PRODS), "rewritten": sum(PRODS[:-1]), "to_engineer": PRODS[-1] if PRODS else 0}}

def answer(claim_raw, obj=None):
    """17.10: П-9 — трасса пункта в out["trace"]; разбор — _answer (не тронут)."""
    TRACE.clear(); NUMS.clear(); PRODS.clear(); t0 = time.time()
    claim, _ = anonymize(claim_raw)
    if not R8.candidates(claim) and not R8.reg_candidates(claim):   # 17.10: П-8 — пустой поиск: явная причина, модель не зовём
        out = empty_search(claim_raw, obj); out["trace"] = trace(time.time() - t0); return out, []
    try: out, usage = _answer(claim_raw, obj)
    except ModelError as e: out, usage = degraded(claim_raw, obj, e), []   # 17.10: П-5 — деградация вместо тишины
    if str(out["internal"].get("reason") or "").startswith("ошибка вызова"):   # сбой на вердикте ловит analyze — тоже тревога (П-7)
        out["internal"]["model_error"] = "verdict: " + out["internal"]["reason"]
    out["trace"] = trace(time.time() - t0)
    return out, usage

