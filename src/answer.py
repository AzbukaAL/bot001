    mat = material_conflict(a["claim"], [b["quote"] for b in client_basis if not b.get("object")] + [str(a.get("evidence") or "")], obj)
    if mat: internal["material_conflict"] = mat   # 18.10: основание о другом материале — покупателю не выдаётся
    extra, w, probs = "", {}, []
    for attempt in range(3):
        w, u = write(a, use_basis, calc, conclusions, extra); usage.append(u)
        probs = check_facts(w, use_basis, calc, a["claim"])
        if not probs: break
        extra = "\n\nПРЕДЫДУЩИЙ ОТВЕТ ОТКЛОНЁН ПРОВЕРКОЙ ФАКТОВ:\n" + "\n".join(f"- {p}: «{s[:120]}»" for s, p in probs) + \
                "\nИсправь: факты — только из оснований/расчёта/претензии, с маркером; рассуждение — без новых фактов."
    internal["draft"] = {k: w.get(k) for k in ("conclusion", "reasoning", "action", "clarify")}
