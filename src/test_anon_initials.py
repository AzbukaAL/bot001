"""Обезличиватель: ФИО с инициалами (19.10.2026, п. 8.3) — «И. Фамилия», «Фамилия И.», «И. О. Фамилия», «Фамилия И. О.»;
ловушки-сокращения не становятся ФИО.  python3 src/test_anon_initials.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from anonymize import anonymize

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)
def tags(t): return re.findall(r"<([А-ЯA-Z]+)_\d+>", anonymize(t)[0])

POS = ["Договор подписал И. Зайцев.", "Звонил Петров И. вчера.", "Ответственный — И. О. Петров.", "Ответственный — Петров И. О.",
       "И.Петров", "Передать Петрову И.", "А. Ковальская уточнит", "Шевченко Т. против", "Акт подписал Д.И. Грушко", "Орлов И. И.",
       "Мнение К. Смирновой", "Спросить у Беридзе Г.", "Оплатил Ивановым С. счёт"]
for t in POS: check(f"маскируется: {t}", "ФИО" in tags(t))
NEG = ["см. п. 7.8 СП 17", "СП 17.13330.2017", "т. е. так", "и т. д.", "с. 12", "г. Ростов-на-Дону", "Т. 1", "рис. 5", "табл. 3",
       "прил. Б", "Приложение Б. Таблица Б.6", "по таблице В.1 СП 64", "т. к. нет", "и т. п.", "и др.", "Н. Новгород", "В. Новгород",
       "ст. 12", "им. Гагарина", "Раздел А. Общие положения", "Т. е. так", "Б. Таблица", "П. 4.2 гласит",
       "нужен автомат 63–80 А. Классический случай", "ток 25 А. Российский стандарт", "до 32А. Типовой случай"]   # 19.10: амперы в конце предложения
for t in NEG: check(f"не ФИО: {t}", "ФИО" not in tags(t))
check("ул. Ленина — адрес, как прежде, не ФИО", tags("ул. Ленина") == ["АДРЕС"])
check("сотрудник заказчика С. Бердников — не маскируется", tags("инженер заказчика С. Бердников, 19.10.2026") == [])
check("Алексей Самсонов — как прежде", tags("Алексей Самсонов") == [])
check("обращение «Вас» — как прежде", tags("У Вас в КП") == [])
print(f"ФИО с инициалами: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
