"""Утверждение о продукте со ссылкой — цитата по ссылке о том же предмете (21.10.2026, решение Вадима). Случай — регресс
21.10: K061 ушёл покупателю с «Базовая дверь выбирается с учётом всех этих характеристик [1]», [1] — СК-ЧБ §7.5 про двери
вообще.  python3 src/test_product_subject.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import answer as A

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)

Q75 = ("Терморазрыв уменьшает передачу холода через металлические элементы полотна и коробки и позволяет снизить вероятность "
       "сильного охлаждения внутренних поверхностей двери и образования конденсата. При выборе наружной двери учитывается не только "
       "наличие терморазрыва, но и характеристики дверного блока в целом: конструкция полотна и коробки, утепление, количество "
       "контуров уплотнения, герметичность притвора и фактические теплотехнические показатели.")
Q74 = ("По желанию заказчика базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом. Такое решение "
       "особенно рекомендуется для домов постоянного проживания и регионов с холодным климатом.")
B = [{"label": "СК", "quote": Q75, "standard": True}, {"label": "СК", "quote": Q74, "standard": True}]
def probs(t, basis=B, field="reasoning"): return A.product_problems({field: t}, basis)

p = probs("Базовая дверь выбирается с учётом всех этих характеристик [1].")
check("K061: «базовая дверь … [1]» с §7.5 — ловится", len(p) == 1 and "нет «базов…»" in p[0][1])
check("K061: причина — та же «утверждение о продукте без основания»", p and p[0][1].startswith(A.PRODUCT_WHY))
check("§7.4: «базовая дверь может быть заменена на улучшенную с терморазрывом [2]» — проходит",
      not probs("Базовая дверь может быть заменена на улучшенную металлическую дверь с терморазрывом [2]."))
check("пересказ §7.4 своими словами со ссылкой [2] — проходит (в цитате есть «базов…»)",
      not probs("Базовую дверь можно по желанию заменить на дверь с терморазрывом [2]."))
check("несколько ссылок: «базов…» есть в одной из них — проходит", not probs("Базовая дверь подходит не всем, есть опция [1][2]."))
check("«Коротко» K061 из регресса — ловится", bool(probs("В базовой комплектации дверь оценивается по комплексу характеристик "
      "(утепление, уплотнение, герметичность), а не только по терморазрыву [1].", field="short")))
check("ссылка только на расчёт [Р] — как раньше (не проверяется)", not probs("Мощность котла подобрана по расчёту [Р]."))
check("без ссылки — как раньше ловится", bool(probs("Базовая дверь подобрана по климату.")))
KP = [{"label": "Данные Вашего проекта (КП)", "quote": "Двери входные: с термо разрывом", "object": True}] + B
check("сравнение с КП — исключение 09.10, как раньше", not probs("Ваше замечание не соответствует данным проекта [1].", KP))
print(f"тот же предмет по ссылке: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
