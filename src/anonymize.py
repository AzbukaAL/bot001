"""Обезличивание текста перед моделью и перед любым выводом (договор, п. 8.3: ФИО, телефоны, адреса покупателей
в модель не передаются). Консервативно: лучше замаскировать лишнее, чем пропустить.
Метки обратимы для сборки ответа: anonymize() возвращает (текст, словарь метка→оригинал)."""
import re

# 19.10.2026: фамилия — по окончанию, с падежными формами (Бердников / Бердникову / Бердниковым, Ковальская, Шевченко)
SURNAME = (r"[А-ЯЁ][а-яё]+(?:(?:ов|ев|ёв|ин|ын)(?:а|у|ым|ой|ом|е|ых|ыми)?"
           r"|(?:ск|цк)(?:ий|ого|ому|им|ом|ая|ой|ую)"
           r"|(?:енко|ко|юк|ук|ич|ян|дзе|швили|их|ых))")
# 21.10.2026 (п. 8.3, решение Вадима): паспорт — ПЕРВЫМИ, раньше телефона и адреса. Найден в смете 52Р5 (приложение к
# договору другого покупателя): обезличиватель паспорт не знал. Слитные 10 цифр и «серия … №» — только рядом со словами
# паспорт / серия / выдан (иначе ИНН организации, артикулы); «60 12 345678» с пробелами — всегда.
PASS_CTX = r"(?:паспорт\w*|серия|серии)"
PATTERNS_PASSPORT = [
    ("ПАСПОРТ", re.compile(r"(?i)" + PASS_CTX + r"[\s:.,]{0,15}(?:РФ[\s:.,]{0,5})?\d{2}\s?\d{2}\s*(?:№|N|номер)?\s*\d{6}\b")),
    ("ПАСПОРТ", re.compile(r"(?<![\d.,])\b\d{2}\s\d{2}\s\d{6}\b(?![.,]?\d)")),
    ("ПАСПОРТ", re.compile(r"(?i)\bвыдан\w*\b[^\n]{0,160}?(?:\d{2}\.\d{2}\.\d{2,4}(?:\s*г\.?)?|\d{3}-\d{3})"
                           r"(?:[^\n]{0,40}?(?:\d{2}\.\d{2}\.\d{2,4}(?:\s*г\.?)?|\d{3}-\d{3}))?")),
    ("ПАСПОРТ", re.compile(r"(?i)\bвыдан\w*\b[^\n]{3,160}")),   # «выдан …» без даты и кода — до конца строки
    ("ПАСПОРТ", re.compile(r"(?i)код\s+подразделени\w*[\s:.,]{0,5}\d{3}-\d{3}")),
    ("ПАСПОРТ", re.compile(r"(?i)дата\s+выдачи[\s:.,]{0,5}\d{2}\.\d{2}\.\d{2,4}")),
]
# 21.10.2026: адрес участка в договорных документах — «(расположенного) по адресу: …» до конца строки и кадастровый
# номер (смета 52Р5: «…по адресу: Ростовская обл, р-н …, г …, сад …, кадастровый номер 61:54:…» — шаблон «ул./д./кв.» не ловил)
PATTERNS_ADDRESS = [
    ("АДРЕС", re.compile(r"(?i)кадастров\w*\s+(?:номер\w*|№)[\s:]{0,5}\d{2}:\d{2}:\d{5,7}:\d+")),
    ("АДРЕС", re.compile(r"\b\d{2}:\d{2}:\d{6,7}:\d{1,6}\b")),   # кадастровый номер без подписи
    ("АДРЕС", re.compile(r"(?i)адрес\w*\s+(?:регистрации|прописки|проживания|места\s+жительства|фактического\s+проживания)[\s:]{0,3}[^\n]{0,200}")),
    ("АДРЕС", re.compile(r"(?i)(?<=по\sадресу)[\s:]{1,3}[^\n]{3,200}")),
    ("АДРЕС", re.compile(r"(?i)(?<=\bадрес)[\s:]{1,3}(?=[^\n]*\d)[^\n]{3,200}")),   # «адрес: …» с цифрами (дом, индекс)
]
PATTERNS = PATTERNS_PASSPORT + PATTERNS_ADDRESS + [
    ("EMAIL", re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")),
    ("ТЕЛ", re.compile(r"(?:\+7|\b8)[\s(\-]*\d{3}[\s)\-]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}\b")),
    ("АДРЕС", re.compile(r"\b(?:ул\.|улица|пр-кт|проспект|пер\.|переулок|ш\.|шоссе|мкр\.?|микрорайон)\s*[А-ЯЁA-Z][\w\-.]*(?:\s+[А-ЯЁ][\w\-.]*)?"
                         r"(?:\s*,?\s*(?:д\.|дом)\s*\d+[\w/]*)?(?:\s*,?\s*(?:кв\.|квартира)\s*\d+)?", re.I)),
    ("АДРЕС", re.compile(r"\b(?:д\.|дом)\s*\d+[\w/]*\s*,?\s*(?:кв\.|квартира)\s*\d+", re.I)),
    ("ФИО", re.compile(r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.")),
    ("ФИО", re.compile(r"\b[А-ЯЁ]\.\s*[А-ЯЁ]\.\s*[А-ЯЁ][а-яё]+")),
    ("ФИО", re.compile(r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:вич|вна|ична|оглы|кызы)\b")),
    # 19.10.2026: один инициал — «И. Фамилия», «Фамилия И.» (раньше маскировались только формы с двумя инициалами).
    # Слово рядом с инициалом должно выглядеть как фамилия (окончание), иначе «приложение Б. Таблица», «Т. 1» и т. п.
    ("ФИО", re.compile(r"(?<![\d–-]\s)(?<![\d–-])\b[А-ЯЁ]\.\s?" + SURNAME + r"\b")),   # не после числа: «80 А. Классический случай»
    ("ФИО", re.compile(r"\b" + SURNAME + r"\s+[А-ЯЁ]\.(?![А-ЯЁа-яё])")),
    ("ФИО", re.compile(r"(?<=\bУважаем(?:ый|ая)\s)[А-ЯЁ][а-яё]+(?:\s+[А-ЯЁ][а-яё]+)?")),
]
# Одиночные имена (обращение «Маша, …», «Сергей, …») — ПДн покупателя; частые имена и уменьшительные.
NAMES = ("Александр Саша Алексей Лёша Леша Анатолий Андрей Антон Аркадий Артём Артем Богдан Борис Вадим Валентин Валерий Василий Вася "
         "Виктор Виталий Владимир Вова Владислав Влад Вячеслав Геннадий Гена Георгий Глеб Григорий Даниил Данил Денис Дмитрий Дима Евгений Женя "
         "Егор Иван Ваня Игорь Илья Кирилл Константин Костя Лев Леонид Максим Макс Марк Михаил Миша Никита Николай Коля Олег Павел Паша Пётр Петр "
         "Роман Рома Руслан Семён Семен Сергей Серёжа Сережа Станислав Стас Степан Тимур Тимофей Фёдор Федор Юрий Юра Ярослав "
         "Алла Алина Алёна Алена Александра Алиса Анастасия Настя Ангелина Анна Аня Валентина Валерия Вера Вероника Виктория Вика Галина Маша "
         "Дарья Даша Евгения Екатерина Катя Елена Лена Елизавета Лиза Жанна Зоя Инна Ирина Ира Карина Кристина Ксения Ксюша Лариса Лидия "
         "Любовь Люба Людмила Люда Маргарита Рита Марина Мария Маша Надежда Надя Наталья Наташа Нина Оксана Ольга Оля Полина Раиса Светлана Света "
         "Софья Соня Тамара Татьяна Таня Ульяна Юлия Юля Яна").split()
# 07.10.2026: имя ловится и в косвенных падежах («для Анны и Ивана» прошло — словарь знал только именительный).
# Основа = имя без конечной гласной / й / ь; дальше любое падежное окончание.
def _stem(n): return n[:-1] if n[-1] in "аяйь" else n
_ENDS = r"(?:а|я|у|ю|ы|и|е|ё|ой|ей|ою|ею|ом|ем|ём|ь|й)?"
PATTERNS.append(("ИМЯ", re.compile(r"\b(?:" + "|".join(sorted({_stem(n) for n in NAMES}, key=len, reverse=True)) + r")" + _ENDS + r"\b")))

# Сотрудники заказчика и названия объектов — НЕ ПДн покупателей, их не трогаем.
ALLOW = {"Алексей", "Алексея", "Алексею", "Алексеем", "Алексее", "Самсонов", "Алексей Самсонов", "Каменское", "Каменского", "Каменском", "Крым", "Крыму",
         "Вас", "С. Бердников", "Бердников С."}   # 19.10: инженер заказчика (одиночный инициал теперь маскируется)   # 12.10.2026: «Вас» с заглавной попадало под основу имени «Вася» — ложная метка в вежливом обращении;
                  # падежные формы «Васи/Васе/Васю/Васей» маскируются как прежде (ALLOW — точное совпадение)

def anonymize(text):
    mapping, n = {}, {}
    def sub(kind):
        def f(m):
            s = m.group(0)
            if s in ALLOW: return s
            n[kind] = n.get(kind, 0) + 1
            tag = f"<{kind}_{n[kind]}>"; mapping[tag] = s
            return tag
        return f
    for kind, rx in PATTERNS:
        text = rx.sub(sub(kind), text)
    return text, mapping

if __name__ == "__main__":
    t, m = anonymize("Иванов И.И., тел. +7 988 111-22-33, ул. Ленина д. 5 кв. 7, Алексей Самсонов, почта a@b.ru")
    print(t); print(sorted(m))
