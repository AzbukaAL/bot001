"""wip/index-fix (17.10.2026): склейка переносов при сборке индекса и в сверке дословности; ROUTE по границам слов;
лимит ответа вердикта; короткий ответ «не относится».  python3 src/test_index_fix.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import normy_parse as NP, run08 as R8, answer as A

ok = 0; fail = []
def check(name, cond):
    global ok
    if cond: ok += 1
    else: fail.append(name)

# а) склейка при сборке индекса
J = NP.join_hyphens
check("перенос слога", J("с учетом уси-\nлия на выдергивание") == "с учетом усилия\nна выдергивание")
check("настоящий дефис по словарю", J("физико-механических свойств; физико-\nмеханических") .endswith("физико-механических\n"))
check("склейка по словарю", J("поверхности и по-\nверхности").endswith("поверхности\n"))
check("пунктуация уходит со словом", J("проекции кров-\nли. Далее") == "проекции кровли.\nДалее")
# строка заголовка пункта не получает хвост следующей строки (иначе кончается числом и читается как оглавление)
secs, pts = NP.parse("4.4 Площадь продухов не менее 1/300 площади.\n4.5 Высота каналов между теплоизоляцией и ос-\nнованием зависит от длины ската 12\n4.6 Дальше")
check("пункт после переноса не пропал", set(pts) == {"4.4", "4.5", "4.6"} and "основанием" in pts["4.5"]["text"])
# остаток строки с номером не становится ложным пунктом
secs, pts = NP.parse("5.5.4.1 Освещенность следует принимать по таб-\nлице 7.23 СП 52.13330.2016.\n5.5.4.2 Другое")
check("номер в остатке строки — не пункт", set(pts) == {"5.5.4.1", "5.5.4.2"} and "таблице 7.23 СП 52" in pts["5.5.4.1"]["text"])
secs, pts = NP.parse("11.1.11 Коэффициент по таб-\nлице\n11.7. Рисунок")
check("номер в конце строки — не пункт", "11.1.11" in pts and "таблице" in pts["11.1.11"]["text"])
check("переносы с прописной не трогаем", J("СП-\nОбщие") == "СП-\nОбщие")

# а) та же нормализация в сверке дословности
check("unhyph: перенос", R8.unhyph("с учетом уси- лия на") == "с учетом усилия на")
check("unhyph: слитный дефис не трогает", R8.unhyph("административно-бытовых") == "административно-бытовых")
src = "Расчет выполняют на ветровую нагрузку с учетом уси- лия на выдергивание кляммера. Максимальное расстояние 600 мм."
check("цитата через перенос находится", (A.full_sentence_quote(src, "с учетом усилия на выдергивание кляммера") or "").startswith("Расчет выполняют"))

# б) run08.ROUTE — по границам слов, «а» не электрика
import re
EL = [rx for rx, d in R8.ROUTE if "СП 256.1325800.2016" in d][0]
for t, want in [("Стены утеплены, а кровля — нет", False), ("А кровля протечёт", False), ("поток воздуха в канале", False),
                ("автомат 25 А мал", True), ("ток 22,8 А", True), ("ввод 15 кВт на три фазы", True)]:
    check(f"ROUTE электрика: «{t}» → {want}", bool(re.search(EL, t, re.I)) == want)
WOOD = [rx for rx, d in R8.ROUTE if any("64.13330" in x for x in d)]
check("ROUTE: «влага» не деревянные конструкции", not WOOD or not re.search(WOOD[0], "влага в утеплителе", re.I))
check("ROUTE: «лаги» — деревянные конструкции", not WOOD or bool(re.search(WOOD[0], "лаги пола", re.I)))
# г) «не относится» — короткий ответ кодом
KP = {"object": True, "label": "Данные Вашего проекта (КП)", "quote": "Окна: стеклопакет 4-10-4-10-4И"}
NORM = {"object": False, "label": "СП 50", "quote": "…"}
w = {"conclusion": A.NOT_APPLICABLE, "action": "Мы ставим", "clarify": "Уточните",
     "reasoning": "Вы пишете об однокамерном стеклопакете, но в Вашем проекте заложен двухкамерный 4-10-4-10-4И [1]. "
                  "Это решение снижает риск конденсата за счёт более высокой температуры стекла [2]."}
r = A.na_short(w, [KP, NORM], "Однокамерный будет потеть. Нужен двухкамерный стеклопакет.")
check("не относится: только «что заложено» + фраза", r["reasoning"] == "Вы пишете об однокамерном стеклопакете, но в Вашем проекте заложен двухкамерный 4-10-4-10-4И [1]. " + A.SAME_AS_PROPOSED)
check("не относится: без «что делаем/уточнить»", r["action"] is None and r["clarify"] is None)
check("не относится: причинных слов нет", not A.CAUSAL.search(r["reasoning"]))
check("без предложения покупателя — без фразы", A.SAME_AS_PROPOSED not in A.na_short(w, [KP, NORM], "Однокамерный стеклопакет будет потеть.")["reasoning"])
check("нет ссылки на проект — не трогаем", A.na_short(dict(w, reasoning="Общая фраза [2]."), [KP, NORM], "Нужен")["reasoning"] == "Общая фраза [2].")
check("фраза модели не дублируется", A.na_short(dict(w, reasoning="Заложен двухкамерный [1]. То есть именно то, что Вы предлагаете."), [KP], "x")["reasoning"].count("именно то") == 1)
# д) предлог из заголовка перечня в части цитаты
SRC = "свод правил устанавливает требования: - к приведенному сопротивлению теплопередаче; - ограничению минимальной температуры и недопущению конденсации влаги"
check("перечень: «к ограничению …» находится", R8.part_found("к ограничению минимальной температуры и недопущению", SRC))
check("перечень: чужое слово в начале — нет", not R8.part_found("по ограничению максимальной температуры", SRC))
check("перечень: только предлог — нет", not R8.part_found("к ограничению", SRC))
check("перечень: искажение после предлога — нет", not R8.part_found("к ограничению минимальной влажности воздуха", SRC))
print(f"правка индекса: {ok}/{ok + len(fail)}", "" if not fail else f"ПРОВАЛ: {fail}")
sys.exit(1 if fail else 0)
